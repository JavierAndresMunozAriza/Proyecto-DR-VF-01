#!/usr/bin/env python3
"""Generate test_vectors.txt for the fence codec.

This is an independent implementation of the wire format in fence_codec.h
(it uses zlib for the CRC), so the C tests cross-check the C codec against it.
The browser portal reuses the same vectors.

Usage: python3 -I gen_vectors.py > test_vectors.txt
"""

import math
import struct
import zlib

LAT0 = 46097000      # 4.6097 deg, in 1e-7 deg
LON0 = -740817000    # -74.0817 deg
UNIT = 10            # delta unit, in 1e-7 deg


def rdiv(a, b):
    """Integer division rounding half away from zero (same as the C code)."""
    q = (abs(a) + b // 2) // b
    return q if a >= 0 else -q


def build(vertices, version=1, flags=0, fence_id=7, fence_version=3,
          n_override=None):
    """Encode absolute (lat, lon) vertices in 1e-7 deg into a blob."""
    n = len(vertices) if n_override is None else n_override
    body = struct.pack("<BBHII", version, flags, n, fence_id, fence_version)
    lat, lon = vertices[0]
    body += struct.pack("<ii", lat, lon)
    prev_lat, prev_lon = lat, lon
    for lat, lon in vertices[1:]:
        dlat = rdiv(lat - prev_lat, UNIT)
        dlon = rdiv(lon - prev_lon, UNIT)
        body += struct.pack("<hh", dlat, dlon)
        prev_lat += dlat * UNIT
        prev_lon += dlon * UNIT
    return body + struct.pack("<I", zlib.crc32(body) & 0xFFFFFFFF)


def at(points):
    return [(LAT0 + a, LON0 + b) for a, b in points]


def circle(n, radius):
    return at([(round(radius * math.sin(2 * math.pi * i / n)),
                round(radius * math.cos(2 * math.pi * i / n)))
               for i in range(n)])


SQUARE = at([(0, 0), (0, 5400), (5400, 5400), (5400, 0)])
L_SHAPE = at([(0, 0), (0, 8000), (3000, 8000), (3000, 3000), (8000, 3000),
              (8000, 0)])


def corrupt_byte(blob, index):
    b = bytearray(blob)
    b[index] ^= 0xFF
    return bytes(b)


def fix_crc(blob):
    body = blob[:-4]
    return body + struct.pack("<I", zlib.crc32(body) & 0xFFFFFFFF)


def main():
    good = build(SQUARE)
    vectors = [
        ("square_ccw", "OK", good),
        ("square_cw", "OK", build(list(reversed(SQUARE)))),
        ("l_shape", "OK", build(L_SHAPE)),
        ("circle_3", "OK", build(circle(3, 4500))),
        ("circle_128_max", "OK", build(circle(128, 4500))),
        # A 3 km edge (270000 units) still fits: the delta limit is 3.6 km.
        ("long_edge_3km", "OK", build(at([(0, 0), (0, 270000),
                                         (6000, 270000), (6000, 0)]))),
        ("too_short", "SIZE", good[:10]),
        ("truncated", "SIZE", good[:-1]),
        ("extra_byte", "SIZE", good + b"\x00"),
        ("bad_crc", "CRC", corrupt_byte(good, 22)),
        ("bad_version", "FORMAT", fix_crc(build(SQUARE, version=2))),
        ("bad_flags", "FORMAT", fix_crc(build(SQUARE, flags=1))),
        ("two_vertices", "VERTEX_COUNT", build(SQUARE[:2])),
        ("circle_129", "VERTEX_COUNT", build(circle(129, 4500))),
        ("lat_86", "RANGE", build([(860000000, LON0), (860000000, LON0 + 5400),
                                   (860005400, LON0 + 5400)])),
        ("lon_180_5", "RANGE", build([(LAT0, 1805000000),
                                      (LAT0, 1805005400),
                                      (LAT0 + 5400, 1805005400)])),
        ("bowtie", "NOT_SIMPLE", build(at([(0, 0), (0, 6000), (6000, 0),
                                           (6000, 6000)]))),
        ("repeated_vertex", "NOT_SIMPLE",
         build(at([(0, 0), (0, 0), (6000, 0), (6000, 6000)]))),
        ("vertex_on_edge", "NOT_SIMPLE",
         build(at([(0, 0), (0, 6000), (6000, 6000), (6000, 0), (0, 3000)]))),
        ("tiny_area", "AREA", build(at([(0, 0), (0, 200), (200, 0)]))),
    ]
    print("# name expect hex   (generated by gen_vectors.py, do not edit)")
    for name, expect, blob in vectors:
        print(f"{name} {expect} {blob.hex()}")


if __name__ == "__main__":
    main()
